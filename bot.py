_TEMPLATE_ERRORS = (KeyError, IndexError, ValueError, AttributeError)


def reminder_template(days_left):
    """Какой текст брать: за столько-то дней или перед началом (days_left=None)."""
    if days_left is None:
        return TEXT_REMINDER_SOON
    return TEXT_REMINDERS.get(days_left, TEXT_REMINDER_DEFAULT)


def reminder_text(w, when: str, template: str):
    """Текст напоминания про вебинар w. Возвращает (текст, что сказать группе).

    Тексты правит владелец, поэтому ни ошибка в фигурных скобках, ни
    незаполненная ссылка не должны останавливать рассылку: напоминание
    уходит в упрощённом виде, а в группу уходит предупреждение.
    """
    zoom = (w.get("zoom") or "").strip()
    note = None
    if "{zoom}" in template and not zoom:
        # Ссылки нет — шлём текст без неё, иначе люди получат «Ссылка: »
        logger.error("У вебинара %s не заполнена ссылка на зум", webinar_key(w))
        template = TEXT_REMINDER_DEFAULT
        note = TEXT_GROUP_NO_ZOOM.format(
            webinar=html.escape(key_label(webinar_key(w))), field="\"zoom\"")
    try:
        return template.format(when=when, time=w["time"],
                               title=clean_title(w), zoom=zoom), note
    except _TEMPLATE_ERRORS as e:
        logger.error("Ошибка в тексте напоминания: %r — шлю запасной", e)
        return (TEXT_REMINDER_FALLBACK.format(
                    when=when, time=w["time"], title=clean_title(w)),
                TEXT_GROUP_REMINDER_TEMPLATE_BROKEN.format(
                    error=html.escape(str(e))))


def warn_markup(bot, error) -> None:
    """Сообщает в группу, что Телеграм не понял разметку напоминания."""
    notify_group(bot, TEXT_GROUP_REMINDER_MARKUP_BROKEN.format(
        error=html.escape(str(error))))


# О каком напоминании уже написали «не дошло ни до кого». Напоминание «перед
# началом» проверяется каждые 5 минут — без этого группа получала бы по
# сообщению на каждую неудачную попытку.
_reported_not_sent = set()


def report_not_sent(bot, tag: str, label: str, failed: int) -> None:
    """Одно сообщение в группу на напоминание, которое не дошло ни до кого."""
    if tag in _reported_not_sent:
        return
    _reported_not_sent.add(tag)
    notify_group(bot, TEXT_GROUP_REMINDER_NOT_SENT.format(
        date=label, failed=failed))


# Как часто, пока сервис не спит, проверять, не пора ли напоминание «перед
# началом». Имя — чтобы /stats нашёл эту проверку в расписании.
SOON_CHECK_MINUTES = 5
SOON_JOB_NAME = "soon"

# Напоминания рассылаются по одному: «перед началом» проверяется в своём
# потоке, и ручной /check в ту же минуту отправил бы то же самое ещё раз —
# отметка «отправлено» ставится только после всей рассылки.
_reminder_lock = threading.Lock()
_reported_blocked = False    # уже сказали группе, что список не прочитан


def registry_ready(bot) -> bool:
    """Прочитан ли список — перед тем как решать, кому напоминать.

    Если на холодном старте чтение сорвалось, в памяти пусто, и напоминание
    решило бы, что записавшихся нет, — и молча не ушло бы никому. Поэтому
    перечитываем; не вышло — один раз говорим группе и ничего не отмечаем.
    """
    global _reported_blocked
    with _save_lock:          # чтобы чтение не разминулось с сохранением
        ok = registry_loaded or load_registry(bot)
    if ok:
        _reported_blocked = False
    elif not _reported_blocked:
        _reported_blocked = True
        notify_group(bot, TEXT_GROUP_REMINDERS_BLOCKED.format(
            minutes=SOON_CHECK_MINUTES))
    return ok


def link_reminders_done(key: str) -> bool:
    """Все напоминания со ссылкой по этому вебинару уже ушли?

    Если да, то записавшийся сейчас не получит уже ничего: напоминания
    рассылаются один раз и повторно не уходят. Значит, ссылку надо дать ему
    сразу при регистрации.
    """
    if REMINDER_BEFORE_START:
        return sent_tag(key, "soon") in reminded_keys
    if REMINDER_DAYS:
        return sent_tag(key, f"d{min(REMINDER_DAYS)}") in reminded_keys
    return True          # напоминаний нет вовсе — ссылка нужна сразу


def send_link_now(bot, w, user_id: int) -> bool:
    """Шлёт записавшемуся то же напоминание «скоро», что получили остальные."""
    text, note = reminder_text(w, TEXT_WHEN_SOON, reminder_template(None))
    if note:
        notify_group(bot, note)
    sent, _, markup_error = broadcast(bot, text, {user_id},
                                      markup_fallback=True)
    if markup_error:
        warn_markup(bot, markup_error)
    return bool(sent)


def send_reminders(bot, today: datetime.date = None) -> int:
    """Напоминания «за N дней» — у каждого вебинара за столько дней, сколько
    указано в REMINDER_DAYS. Возвращает, скольким людям ушло."""
    with _reminder_lock:
        return _send_reminders(bot, today)


def _send_reminders(bot, today: datetime.date = None) -> int:
    if today is None:
        today = today_local()

    total = 0
    warned = set()   # о какой поломке шаблона уже написали в группу
    for w in WEBINARS:
        webinar_date = parse_date(w["date"])
        if webinar_date is None:
            continue
        days_left = (webinar_date - today).days
        if days_left not in REMINDER_DAYS:
            continue
        # Список — раньше отметок: отметки «отправлено» лежат в нём же, и без
        # него уже отправленное напоминание ушло бы второй раз
        if not registry_ready(bot):
            return total

        key = webinar_key(w)
        tag = f"d{days_left}"
        if sent_tag(key, tag) in reminded_keys:
            logger.info("Напоминание про %s за %s дн. уже отправляли",
                        key, days_left)
            continue

        recipients = reachable(registered_for(key))
        if not recipients:
            # Намеренно НЕ помечаем как отправленное: иначе /stats покажет
            # "напоминание уже отправлено" там, где не ушло ничего, а тот, кто
            # запишется позже в тот же день, уже ничего не получит даже по
            # ручной команде /check.
            logger.info("На вебинар %s никто не записался — напоминать некому",
                        key)
            continue

        text, note = reminder_text(w, when_phrase(days_left),
                                   reminder_template(days_left))
        if note and note not in warned:
            notify_group(bot, note)
            warned.add(note)
        sent, failed, markup_error = broadcast(bot, text, recipients,
                                               markup_fallback=True)
        if markup_error and "markup" not in warned:
            warn_markup(bot, markup_error)
            warned.add("markup")
        total += sent

        logger.info("Напоминание про %s за %s дн.: доставлено %s, ошибок %s",
                    key, days_left, sent, failed)
        label = f"{w['date']} в {w['time']} ({when_phrase(days_left)})"
        if not sent:
            # Не дошло ни до кого — не отмечаем, чтобы /check мог повторить.
            report_not_sent(bot, sent_tag(key, tag), label, failed)
            continue
        reminded_keys.add(sent_tag(key, tag))
        save_registry(bot)
        notify_group(bot, TEXT_GROUP_REMINDER_SENT.format(
            date=label, sent=sent, failed=failed))
    return total


def when_phrase(days_left: int) -> str:
    """«завтра» / «через 5 дней» — в {when} шаблона напоминания."""
    if days_left <= 1:
        return TEXT_WHEN_TOMORROW
    return TEXT_WHEN_DAYS.format(
        days=f"{days_left} " + plural_ru(days_left, "день", "дня", "дней"))


def send_start_reminders(bot, now: datetime.datetime = None) -> int:
    """Напоминание незадолго до начала вебинара.

    Проверяем окном, а не точной минутой: бесплатный сервис спит и может
    проснуться в любой момент внутри окна — напоминание всё равно уйдёт,
    и ровно один раз.
    """
    with _reminder_lock:
        return _send_start_reminders(bot, now)


def _send_start_reminders(bot, now: datetime.datetime = None) -> int:
    if now is None:
        now = now_local()

    total = 0
    warned = set()   # о какой поломке шаблона уже написали в группу
    for w in WEBINARS:
        # Начало — по WEBINAR_TIMEZONE, now — по TIMEZONE: разность двух
        # точных моментов от поясов не зависит.
        start = webinar_start(w)
        if start is None:
            continue
        minutes_left = (start - now).total_seconds() / 60
        if not 0 < minutes_left <= MINUTES_BEFORE_START:
            continue
        # Список — раньше отметок (см. _send_reminders)
        if not registry_ready(bot):
            return total

        key = webinar_key(w)
        if sent_tag(key, "soon") in reminded_keys:
            continue

        recipients = reachable(registered_for(key))
        if not recipients:
            logger.info("На вебинар %s никто не записался — напоминать некому",
                        key)
            continue

        text, note = reminder_text(w, TEXT_WHEN_SOON, reminder_template(None))
        if note and note not in warned:
            notify_group(bot, note)
            warned.add(note)
        sent, failed, markup_error = broadcast(bot, text, recipients,
                                               markup_fallback=True)
        if markup_error and "markup" not in warned:
            warn_markup(bot, markup_error)
            warned.add("markup")
        total += sent

        logger.info("Напоминание перед началом %s: доставлено %s, ошибок %s",
                    key, sent, failed)
        label = f"{w['date']} в {w['time']} (перед началом)"
        if not sent:
            # Не дошло ни до кого — не отмечаем: через 5 минут бот попробует
            # снова, пока не начался вебинар.
            report_not_sent(bot, sent_tag(key, "soon"), label, failed)
            continue
        reminded_keys.add(sent_tag(key, "soon"))
        save_registry(bot)
        notify_group(bot, TEXT_GROUP_REMINDER_SENT.format(
            date=label, sent=sent, failed=failed))
    return total


