def fill_sheet(ws, keys, snap) -> None:
    """Заполняет лист файла: шапка и по строке на каждую запись."""
    ws.append(list(TEXT_FILE_HEADER))
    for cell in ws[1]:
        cell.font = Font(bold=True)
    row = 1
    for key in keys:
        for uid in sorted(snap[key], key=lambda u: (signed_at.get((key, u), ""), u)):
            row += 1
            name, username = people.get(uid, ("", ""))
            ws.cell(row=row, column=1, value=uid)
            # Текст остаётся текстом: имя вроде «=HYPERLINK(...)» openpyxl
            # иначе записал бы формулой, а Excel бы её выполнил.
            for col, value in ((2, key), (3, name), (4, username)):
                cell = ws.cell(row=row, column=col, value=value)
                cell.data_type = "s"
            when = signed_at.get((key, uid))
            if when:
                cell = ws.cell(row=row, column=5, value=datetime.datetime.strptime(
                    when, "%Y-%m-%d %H:%M"))
                cell.number_format = "yyyy-mm-dd hh:mm"
            marks = []
            if (key, uid) in cancelled:
                marks.append(TEXT_FILE_CANCELLED)
            if uid in blocked:
                marks.append(TEXT_FILE_BLOCKED)
            if marks:
                cell = ws.cell(row=row, column=6, value=", ".join(marks))
                cell.data_type = "s"
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:F{row}"
    for letter, width in zip("ABCDEF", (13, 17, 32, 20, 18, 22)):
        ws.column_dimensions[letter].width = width


def registry_xlsx(snap, today: datetime.date = None) -> bytes:
    """registry.xlsx: строка на каждую запись на вебинар, два листа.

    «Записи» — на вебинары, которые ещё впереди; «Архив» — на прошедшие.
    Переезд на «Архив» происходит сам, когда вебинар прошёл, и НИЧЕГО не
    удаляет: для бота оба листа — один и тот же список, и /broadcast по-
    прежнему доходит до всех, и никто не пропадает.
    """
    if today is None:
        today = today_local()
    order = sorted(snap, key=lambda k: (key_date(k) or datetime.date.max, k))
    past = [k for k in order if (key_date(k) or today) < today]
    upcoming = [k for k in order if k not in set(past)]
    wb = Workbook()
    active = wb.active
    active.title = TEXT_FILE_SHEET
    fill_sheet(active, upcoming, snap)
    fill_sheet(wb.create_sheet(TEXT_FILE_SHEET_ARCHIVE), past, snap)
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


def parse_registry_xlsx(data: bytes):
    """registry.xlsx: (записи, люди, время записи, заблокировавшие, отменившие).

    Непонятная строка — ошибка, а не пропуск: это наш собственный файл, и
    испорченный файл нельзя принять за прочитанный.
    """
    regs, ppl, times, blk, cnc = {}, {}, {}, set(), set()
    wb = load_workbook(io.BytesIO(data), read_only=True)
    try:
        # Читаем ВСЕ листы: и «Записи», и «Архив» — для бота это один список.
        rows = []
        for ws in wb.worksheets:
            sheet_rows = ws.iter_rows(values_only=True)
            next(sheet_rows, None)        # заголовки столбцов
            rows.extend(sheet_rows)
        for row in rows:
            if not row or all(v in (None, "") for v in row):
                continue
            uid, key = row[0], str(row[1] or "").strip()
            if isinstance(uid, float) and uid.is_integer():
                uid = int(uid)
            if not isinstance(uid, int) or not _KEY_LINE.match(key + ":"):
                raise ValueError(f"непонятная строка в файле: {str(row[:2])[:60]}")
            key = migrate_key(key)
            regs.setdefault(key, set()).add(uid)
            name = str(row[2] or "") if len(row) > 2 else ""
            username = str(row[3] or "") if len(row) > 3 else ""
            if name or username:
                ppl[uid] = (name, username)
            when = row[4] if len(row) > 4 else None
            if isinstance(when, datetime.datetime):
                times[(key, uid)] = when.strftime("%Y-%m-%d %H:%M")
            elif when:
                times[(key, uid)] = str(when).strip()
            # В «статусе» теперь две разные пометки, поэтому смотрим, какая
            # именно: «любая пометка = заблокировал» пометила бы отменивших
            # запись как заблокировавших и отрезала бы их от всех рассылок.
            status = str(row[5] or "").strip() if len(row) > 5 else ""
            if TEXT_FILE_CANCELLED in status:
                cnc.add((key, uid))
            if TEXT_FILE_BLOCKED in status or (
                    status and TEXT_FILE_CANCELLED not in status):
                blk.add(uid)
    finally:
        wb.close()
    return regs, ppl, times, blk, cnc


def prune_past_sent(today: datetime.date = None) -> int:
    """Отметки о напоминаниях про прошедшие вебинары больше не нужны.

    Теперь они живут в закреплённом сообщении, а оно не резиновое. Напоминание
    про прошедший вебинар уйти уже не может, так что и отметка ни к чему.
    """
    if today is None:
        today = today_local()
    stale = {t for t in reminded_keys
             if (key_date(t.split("@", 1)[0]) or today) < today}
    reminded_keys.difference_update(stale)
    return len(stale)


def load_registry(bot) -> bool:
    """Читает список записавшихся: закреплённое сообщение и файл, на который оно указывает.

    True — прочитали (в том числе «списка ещё нет, он пустой»).
    False — не смогли; писать в этом состоянии нельзя.
    Прочитанное ДОПОЛНЯЕТ память, а не заменяет её: так регистрация, принятая,
    пока группа была недоступна, переживает повторное чтение перед записью.
    """
    global registry_message_id, registry_loaded, file_pointer, prev_pointer
    global last_pin_text
    global _read_failures, _reported_foreign_pin

    if not ADMIN_CHAT_ID:
        logger.error(
            "ADMIN_CHAT_ID не задан! Регистрации НЕ сохраняются, уведомления "
            "в группу НЕ приходят, служебные команды отключены."
        )
        return False

    try:
        chat = bot.get_chat(ADMIN_CHAT_ID)
    except TelegramError as e:
        registry_loaded = False
        logger.error("Не удалось прочитать список подписчиков: %s", e)
        return False

    pinned = chat.pinned_message
    if pinned is None:
        logger.info("Закреплённого списка нет — будет создан при первой регистрации")
        registry_loaded = True
        return True
    if not (pinned.text and pinned.text.startswith(REGISTRY_HEADER)):
        # Закреплено чужое сообщение. Телеграм отдаёт боту только последнее
        # закреплённое, и список мог оказаться под ним. Считать это пустым
        # списком нельзя: следующая регистрация создала бы новый список поверх
        # всех. Новым список бывает, только когда не закреплено ничего.
        registry_loaded = False
        logger.error("Закреплено не наше сообщение (%s) — список за ним не "
                     "виден, НИЧЕГО не пишу", pinned.message_id)
        if not _reported_foreign_pin:
            _reported_foreign_pin = True
            notify_group(bot, TEXT_GROUP_FOREIGN_PIN)
        return False
    _reported_foreign_pin = False

    registry_message_id = pinned.message_id
    sent, pointers, total = parse_registry(pinned.text)

    if "FILE" not in pointers and total:
        # «Всего» говорит, что люди есть, а ссылки на файл нет — читать нечего.
        # Считать это пустым списком нельзя: следующая запись затёрла бы всех.
        registry_loaded = False
        logger.error("В закреплённом сообщении «Всего: %s», но ссылки на файл "
                     "в нём нет — НИЧЕГО не пишу", total)
        return False

    regs, ppl, times, blk, cnc = {}, {}, {}, set(), set()
    if "FILE" in pointers:
        try:
            data = download_registry(bot, pointers["FILE"][1])
            if data[:2] != b"PK":            # xlsx — это zip-архив
                raise ValueError("файл списка не в формате xlsx")
            regs, ppl, times, blk, cnc = parse_registry_xlsx(data)
            count = len(set().union(*regs.values())) if regs else 0
            # «Всего» записано в сообщение тем же сохранением, что и файл.
            # Файл, оборвавшийся на границе строки, разбирается без ошибок,
            # но людей в нём меньше — такой файл прочитанным не считаем.
            if total is not None and count != total:
                raise ValueError(f"в файле {count} чел., а в закреплённом "
                                 f"сообщении — {total}")
        except Exception as e:     # сеть, битый файл, неизвестный формат
            if not isinstance(e, (TelegramError, ValueError,
                                  zipfile.BadZipFile)):
                logger.exception("Неожиданная ошибка при чтении файла списка")
            registry_loaded = False
            _read_failures += 1
            logger.error("Не удалось прочитать файл списка: %s", e)
            # Один сбой на холодном старте обычно проходит сам при следующей
            # записи — в группу пишем, только если не вышло и во второй раз.
            if _read_failures == 2:
                notify_group(bot, TEXT_GROUP_REGISTRY_UNREADABLE.format(
                    error=html.escape(str(e))))
            return False
        file_pointer = pointers["FILE"]
        prev_pointer = pointers.get("PREV")

        for key, ids in regs.items():
            registrations.setdefault(key, set()).update(ids)
        # то, что память уже знает (свежая регистрация), не затираем
        for uid, info in ppl.items():
            people.setdefault(uid, info)
        for pair, when in times.items():
            signed_at.setdefault(pair, when)
        blocked.update(blk)
        cancelled.update(cnc)
    reminded_keys.update(sent)
    # Счета опросов: из закрепа, но то, что память уже насчитала, не теряем
    for pid, (counts, target) in parse_polls(pinned.text).items():
        mine = poll_counts.get(pid, [])
        merged = [max(a, b) for a, b in itertools.zip_longest(
            counts, mine, fillvalue=0)]
        _keep_poll(pid, merged, poll_targets.get(pid) or target)
    last_pin_text = pinned.text
    _read_failures = 0

    logger.info(
        "Загружено (%s): вебинаров с записями %s, человек всего %s, "
        "отправленных напоминаний %s",
        "из файла" if file_pointer else "из закреплённого сообщения",
        len(registrations), len(all_subscribers()), len(reminded_keys),
    )
    registry_loaded = True
    return True


def pin_text(snap) -> str:
    """Закреплённое сообщение: сколько человек, отметки о напоминаниях и
    указатель на файл. Сам список — в файле.

    snap — тот же снимок списка, что ушёл в файл, чтобы «Всего» в сообщении
    и файл никогда не расходились.
    """
    everyone = set().union(*snap.values()) if snap else set()
    lines = [REGISTRY_HEADER, f"Всего: {len(everyone)}", TEXT_REGISTRY_IN_FILE,
             # Отметки о напоминаниях в файле не хранятся — только здесь
             "SENT:" + ",".join(sorted(reminded_keys))]
    if file_pointer:
        lines.append(f"FILE:{file_pointer[0]}:{file_pointer[1]}")
    if prev_pointer:
        lines.append(f"PREV:{prev_pointer[0]}:{prev_pointer[1]}")
    return "\n".join(lines + poll_lines())


# Строка счёта опроса в закрепе. Номер — 8 шестнадцатеричных знаков, поэтому
# со строкой списка («30.09.2026:…») её не спутать — ни этой версии, ни
# старым: они все пропускают строки, которых не знают.
# «POLL:номер:12,3:кому» — «кому» дописано 05.10 и может отсутствовать у
# опросов, начатых раньше.
_POLL_LINE = re.compile(r"^POLL:([0-9a-f]{8}):(\d+(?:,\d+)*)(?::(.*))?$")


def poll_lines():
    lines = []
    for pid, counts in poll_counts.items():
        line = f"POLL:{pid}:{','.join(str(n) for n in counts)}"
        target = (poll_targets.get(pid) or "").replace("\n", " ").strip()
        lines.append(f"{line}:{target}" if target else line)
    return lines


def parse_polls(text: str):
    """Опросы из закреплённого сообщения: {номер: ([12, 3], «кому»)}."""
    polls = {}
    for line in (text or "").split("\n"):
        match = _POLL_LINE.match(line.strip())
        if match:
            polls[match.group(1)] = ([int(n) for n in match.group(2).split(",")],
                                     (match.group(3) or "").strip())
    return polls


def _keep_poll(poll_id, counts, target=None) -> None:
    poll_counts[poll_id] = counts
    if target:
        poll_targets[poll_id] = target
    while len(poll_counts) > POLL_KEEP:
        oldest = next(iter(poll_counts))
        poll_counts.pop(oldest)
        poll_targets.pop(oldest, None)


def _write_poll_lines(bot) -> bool:
    """Переписывает в закрепе только строки POLL. Вызывать под _save_lock.

    Всё остальное остаётся ровно таким, каким его последний раз прочли или
    записали: голос не должен трогать сам список. Иначе «Всего» в закрепе
    могло бы разойтись с файлом, а на такой закреп бот при чтении не
    полагается — и запись на вебинары встала бы.
    """
    global last_pin_text
    if not (registry_loaded and registry_message_id and last_pin_text):
        return False
    kept = [line for line in last_pin_text.split("\n")
            if not line.startswith("POLL:")]
    text = "\n".join(kept + poll_lines())
    if text == last_pin_text:
        return True
    try:
        with_retry(lambda: bot.edit_message_text(
            chat_id=ADMIN_CHAT_ID, message_id=registry_message_id, text=text,
            disable_web_page_preview=True))
    except BadRequest as e:
        if "message is not modified" not in str(e).lower():
            logger.error("Не удалось записать счёт опроса: %s", e)
            return False
    except TelegramError as e:
        logger.error("Не удалось записать счёт опроса: %s", e)
        return False
    last_pin_text = text
    return True


def start_poll(bot, poll_id: str, options: int, target: str = "") -> None:
    """Заводит счёт опроса с нулями — сразу, как только рассылку отправили.

    Тогда «опроса нет в закрепе» значит одно: он старый и вытеснен. Ответ на
    такой придёт в группу без счёта — лучше без счёта, чем с неверным.
    """
    with _save_lock:
        if poll_id not in poll_counts:
            _keep_poll(poll_id, [0] * options, target)
        if not _write_poll_lines(bot):
            # не беда: счёт есть в памяти и запишется с первым же голосом
            logger.warning("Счёт опроса %s пока не записан в закреп", poll_id)


VOTE_FAILED = "failed"        # голос не записан — кнопки оставляем
VOTE_UNKNOWN = "unknown"      # опрос старый, счёта нет — ответ без счёта


def record_vote(bot, poll_id: str, index: int, options: int):
    """Записывает голос: новый счёт списком, VOTE_UNKNOWN или VOTE_FAILED.

    Сначала в закреп, потом всё остальное — как с регистрацией: человеку
    нельзя сказать «спасибо, учли», если голос никуда не записан.
    """
    with _save_lock:
        # Список не прочитан — значит, и счёт неизвестен: «нет такого опроса»
        # тут ещё ничего не значит
        if not (registry_loaded or load_registry(bot)):
            return VOTE_FAILED
        counts = poll_counts.get(poll_id)
        if counts is None:
            return VOTE_UNKNOWN
        counts.extend([0] * (options - len(counts)))
        counts[index] += 1
        if not _write_poll_lines(bot):
            counts[index] -= 1
            return VOTE_FAILED
        return list(counts)


def with_retry(call):
    """Вызов к Телеграму с одним повтором, если он просит подождать недолго.

    В группу нельзя слать больше ~20 сообщений в минуту, а каждое сохранение
    теперь — это ещё и файл. Короткую паузу переждём, длинную — нет.
    """
    try:
        return call()
    except RetryAfter as e:
        if e.retry_after > 15:
            raise
        logger.warning("Телеграм просит подождать %s с — жду и повторяю",
                       e.retry_after)
        time.sleep(e.retry_after + 1)
        return call()


