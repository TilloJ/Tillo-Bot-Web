REPO_BLOB_URL = "https://github.com/TilloJ/Tillo-Bot-Web/blob/main/bot.py"


def source_line(name: str):
    """Номер строки, где начинается WEBINARS, TEXT_REMINDERS и т.п."""
    try:
        with open(__file__, encoding="utf-8") as f:
            for number, line in enumerate(f, 1):
                if re.match(rf"{name}\s*=", line):
                    return number
    except OSError as e:          # файла рядом нет — обойдёмся без номера
        logger.warning("Не удалось найти %s в исходнике: %s", name, e)
    return None


def source_link(name: str, label: str) -> str:
    """Название куском текста, по которому открывается это место на гитхабе.

    Без этого «bot.py» в сообщении Телеграм превращает в ссылку на домен
    .py (Парагвай) — она никуда не ведёт.
    """
    line = source_line(name)
    url = REPO_BLOB_URL + (f"#L{line}" if line else "")
    return f'<a href="{url}">{html.escape(label)}</a>'


