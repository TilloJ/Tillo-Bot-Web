_TIME_ONLY = re.compile(r"^\d{1,2}[:.]\d{2}$")
# Так вебинар записан внутри бота: 30.09.2026-1100. Раз человек это где-то
# видел, он так и напишет — понимаем и такую запись.
_KEY_FORM = re.compile(r"^(\d{2}\.\d{2}\.\d{4})-(\d{1,2})(\d{2})$")
# Похоже на дату, но не распозналось: 30.9.2026, 30.09.26, 30.09
_DATE_LIKE = re.compile(r"^\d{1,2}\.\d{1,2}")


# «/broadcast 30.09.2026 все текст» — всем сеансам этого дня сразу
_ALL_SESSIONS = ("все", "всё")

# Строка-кнопка: [Надпись](https://ссылка). Пишется с начала строки и занимает
# её целиком, поэтому с обычным текстом не путается. Такая же запись внутри
# строки — это просто ссылка в слове, её делает link_markdown().
_BUTTON_LINE = re.compile(r"^\[([^\]\n]+)\]\((\S+)\)\s*$")
# Строка-ответ опроса: [Да] — только скобки, без ссылки после них
_ANSWER_LINE = re.compile(r"^\[([^\]\n]+)\]\s*$")
_INLINE_LINK = re.compile(
    r"\[([^\]\n]+)\]\(((?:https?|tg)://[^\s()<>]+)\)")


def plain_label(text: str) -> str:
    """Надпись на кнопке — обычный текст: теги Телеграм в ней не покажет."""
    return html.unescape(_HTML_TAG.sub("", text)).strip()


def link_only_line(line: str):
    """Строка целиком — одна ссылка со словами? Тогда это кнопка.

    Телеграм на компьютере превращает «[текст](ссылка)» в готовую ссылку
    прямо при наборе, до отправки: скобки исчезают, и бот видит уже ссылку.
    Поэтому кнопкой считаем и такую строку — иначе у человека «делаю кнопку,
    а выходит ссылка», и поделать с этим он ничего не может.
    """
    links = re.findall(r'<a href="([^"]+)">(.*?)</a>', line, re.S)
    if len(links) != 1:
        return None
    url, inner = links[0]
    if plain_label(line) != plain_label(inner):
        return None          # в строке есть что-то кроме самой ссылки
    return plain_label(inner), html.unescape(url)


def link_markdown(body: str) -> str:
    """«[текст](ссылка)» внутри строки — ссылка прямо в слове.

    Так пишут ссылки по привычке из других редакторов, и владелец написал
    именно так. Если на этом тексте уже есть ссылка (её навели прямо в
    Телеграме), второй раз не оборачиваем — просто убираем скобки.
    """
    def one(match):
        label, url = match.group(1), match.group(2)
        if "<a " in label:
            return label
        return f'<a href="{url}">{label}</a>'
    return _INLINE_LINK.sub(one, body)
BUTTON_MAX = 10           # больше в одном сообщении не нужно никому
BUTTON_LABEL_MAX = 64     # дальше Телеграм обрезает надпись


def split_buttons(body: str):
    """Вынимает строки-кнопки из текста: (текст без них, [(надпись, ссылка)], ошибка).

    Текст здесь уже HTML, поэтому и надпись, и ссылку возвращаем к обычному
    виду: в ссылках платёжных систем часто есть «&», а в HTML он записан
    как «&amp;».
    """
    lines, found = body.split("\n"), []     # found: (номер строки, надпись, ссылка)
    for n, line in enumerate(lines):
        match = _BUTTON_LINE.match(line.strip())
        ready = None if match else link_only_line(line.strip())
        if match or ready:
            label, url = ready or (plain_label(match.group(1)),
                                   html.unescape(match.group(2)))
            if not url.startswith(("https://", "http://", "tg://")):
                return body, [], TEXT_BROADCAST_BUTTON_BAD.format(
                    line=html.escape(line.strip()))
            found.append((n, label, url))
            continue
        answer = _ANSWER_LINE.match(line.strip())
        if answer and plain_label(answer.group(1)):
            found.append((n, plain_label(answer.group(1)), None))
    # Опрос — это хотя бы два варианта; одна строка в скобках («[Важно]»)
    # остаётся обычным текстом
    if sum(1 for _, _, url in found if url is None) < 2:
        found = [f for f in found if f[2] is not None]
    # Варианты одного вопроса идут подряд. Текст между ними — значит, вопросов
    # два, а счёт был бы один на всех: отказываем
    answer_rows = [n for n, _, url in found if url is None]
    if answer_rows:
        taken_rows = {n for n, _, _ in found}
        between = [line for n, line in enumerate(lines)
                   if answer_rows[0] < n < answer_rows[-1]
                   and n not in taken_rows and line.strip()]
        if between:
            return body, [], TEXT_BROADCAST_TWO_POLLS
    for _, label, _ in found:
        if len(label) > BUTTON_LABEL_MAX:
            return body, [], TEXT_BROADCAST_BUTTON_LONG.format(
                max=BUTTON_LABEL_MAX, label=html.escape(label))
    if len(found) > BUTTON_MAX:
        return body, [], TEXT_BROADCAST_BUTTON_MANY.format(max=BUTTON_MAX)
    taken = {n for n, _, _ in found}
    kept = [line for n, line in enumerate(lines) if n not in taken]
    return "\n".join(kept).strip(), [(label, url) for _, label, url in found], None


def buttons_markup(buttons, poll_id=None):
    """Кнопки: ссылки — по одной в ряд, ответы опроса — в одну строку.

    У кнопки-ответа вместо ссылки None. В её данные кладём номер опроса и
    номер варианта: всё остальное (сам вопрос, надписи) бот при нажатии
    берёт из того сообщения, на котором нажали, — так ответ переживает и
    перезапуск, и сон сервиса.
    """
    if not buttons:
        return None
    rows, answers = [], []
    for label, url in buttons:
        if url:
            rows.append([InlineKeyboardButton(label, url=url)])
            continue
        button = InlineKeyboardButton(
            label, callback_data=f"pv:{poll_id}:{len(answers)}")
        if not answers:
            rows.append(answers)          # ряд ответов — там, где первый ответ
        answers.append(button)
    # Короткие ответы рядом, как в опросе; длинные — каждый своей строкой
    if answers and sum(len(b.text) for b in answers) > 30:
        at = next(i for i, row in enumerate(rows) if row is answers)
        rows[at:at + 1] = [[b] for b in answers]
    return InlineKeyboardMarkup(rows)


def utf16_len(text: str) -> int:
    """Длина, как её считает Телеграм: эмодзи и редкие буквы — за два знака."""
    return len(text.encode("utf-16-le")) // 2


def command_html(message, rest: str) -> str:
    """Хвост команды вместе с разметкой, которую человек навёл в Телеграме.

    В message.text форматирования нет вовсе: жирный, курсив и «вшитые» в
    слово ссылки Телеграм присылает отдельным списком. Раньше бот читал
    только текст, и всё это молча пропадало — человек писал одно, а людям
    уходило другое. Собираем из списка тот же HTML, каким бот и рассылает.
    Не получилось разобрать — возвращаем голый текст, как было.
    """
    plain = (message.text or "").rstrip()
    if not rest or not plain.endswith(rest):
        return rest
    cut = utf16_len(plain[:len(plain) - len(rest)])
    kept = []
    for e in (message.entities or []):
        end = e.offset + e.length
        if end <= cut or e.type == MessageEntity.BOT_COMMAND:
            continue
        start = max(e.offset, cut)
        kept.append(MessageEntity(type=e.type, offset=start - cut,
                                  length=end - start, url=e.url, user=e.user,
                                  language=e.language))
    if not kept:
        return rest
    try:
        tail = Message(message_id=message.message_id, date=message.date,
                       chat=message.chat, text=rest, entities=kept)
        return tail.text_html
    except Exception:            # разметку не собрать — лучше голый текст
        logger.exception("Не удалось сохранить разметку сообщения")
        return rest


def next_word(text: str):
    """Первое слово и всё остальное: '19:00\\nтекст' -> ('19:00', 'текст').

    Слова разделяет любой пробел, в том числе перенос строки: текст рассылки
    часто начинают с новой строки сразу после даты или времени.
    """
    parts = text.split(None, 1)
    if not parts:
        return "", ""
    return parts[0], (parts[1].strip() if len(parts) > 1 else "")


def split_target(text: str):
    """'30.09.2026 19:00 текст' -> ('30.09.2026', '19:00', 'текст').

    Понимает и '30.09.2026-1900 текст'. Дата и время необязательны; что не
    распознали — остаётся текстом.
    """
    date_str = time_str = ""
    first, tail = next_word(text)
    key_form = _KEY_FORM.match(first)
    if key_form:
        date_str, text = key_form.group(1), tail
        time_str = f"{key_form.group(2)}:{key_form.group(3)}"
    elif _DATE_ONLY.match(first):
        date_str, text = first, tail
        second, tail2 = next_word(text)
        if _TIME_ONLY.match(second):
            time_str, text = second, tail2
    return date_str, time_str, text


def key_time(key: str) -> str:
    """Время сеанса из ключа: '30.09.2026-1900' -> '19:00'."""
    w = find_webinar(key)
    if w:
        return w["time"]
    digits = key.partition("-")[2]
    return f"{digits[:2]}:{digits[2:]}" if len(digits) == 4 else digits


def keys_for(wanted: str):
    """Ключи вебинаров по дате (все в этот день) или по точному ключу.

    Сеансы дня берём и из расписания, и из самого списка: сеанс, который уже
    убрали из расписания, остаётся в списке со своими записавшимися.
    """
    if find_webinar(wanted) and not _DATE_ONLY.match(wanted):
        return [wanted]
    keys = [webinar_key(w) for w in webinars_on(wanted)]
    keys += sorted(k for k in list(registrations)
                   if k.startswith(wanted + "-") and k not in keys)
    # запись из старого формата под самой датой — её тоже учитываем
    if wanted in registrations and wanted not in keys:
        keys.append(wanted)
    return keys


# Когда /who закончил последнюю страницу. Следующую раньше чем через минуту
# не шлём: Телеграм оборвёт её на середине без всякого объяснения.
_last_who_page = 0.0


def who_command(update: Update, context: CallbackContext) -> None:
    """/who [ДД.ММ.ГГГГ [ЧЧ:ММ]] [страница] — карточки записавшихся по WHO_MAX
    на страницу, по именам можно нажимать."""
    if not is_admin_chat(update):
        return

    w_date, w_time, extra = split_target(next_word(update.message.text)[1])
    page = 1
    if re.fullmatch(r"[0-9]+", extra):
        page, extra = int(extra), ""
    if extra or page < 1:
        update.message.reply_text(
            TEXT_WHO_BAD_ARGS.format(text=html.escape(extra or str(page))),
            parse_mode='HTML',
            disable_web_page_preview=True)
        return

    wanted = f"{w_date}-{re.sub(r'[^0-9]', '', w_time)}" if w_time else w_date
    target = f"{w_date} {w_time}" if w_time else w_date   # как пишут после /who
    label = f"{w_date} в {w_time}" if w_time else w_date  # как показываем людям
    if wanted:
        dates = keys_for(wanted)
        if not dates:
            update.message.reply_text(TEXT_WHO_NO_WEBINAR.format(date=label),
                disable_web_page_preview=True)
            return
        if not any(registered_for(k) for k in dates):
            update.message.reply_text(
                TEXT_BROADCAST_EMPTY_ONE.format(date=label),
                disable_web_page_preview=True)
            return
    else:
        dates = sorted(
            (k for k, ids in registrations.items() if ids),
            key=lambda k: (key_date(k) or datetime.date.max, k),
        )
    if not dates:
        update.message.reply_text(TEXT_WHO_EMPTY,
                                  disable_web_page_preview=True)
        return

    # Каждый человек — один раз, сколько бы вебинаров у него ни было.
    on_dates = {}
    for date_str in dates:
        for uid in registered_for(date_str):
            on_dates.setdefault(uid, []).append(date_str)

    # Порядок по id: он не меняется между вызовами, так что страницы не
    # перемешиваются, а имена узнаём только у тех, кто на этой странице.
    people = sorted(on_dates, key=str)
    pages = -(-len(people) // WHO_MAX)
    if page > pages:
        update.message.reply_text(
            TEXT_WHO_NO_PAGE.format(page=page, pages=pages),
            disable_web_page_preview=True)
        return
    first = (page - 1) * WHO_MAX
    chunk = people[first:first + WHO_MAX]

    global _last_who_page
    wait = 60 - (time.time() - _last_who_page)
    if wait > 0:
        update.message.reply_text(TEXT_WHO_WAIT.format(seconds=int(wait) + 1),
                                  disable_web_page_preview=True)
        return
    try:
        _send_who_page(update, context, label, target, page, people, chunk,
                       first, on_dates)
    finally:
        _last_who_page = time.time()


def _send_who_page(update, context, label, target, page, people, chunk,
                   first, on_dates) -> None:
    """Заголовок, карточки и подпись одной страницы /who."""
    try:
        update.message.reply_text(
            TEXT_WHO_HEADER.format(
                scope=TEXT_WHO_SCOPE.format(date=label) if label else ""),
            parse_mode='HTML', disable_web_page_preview=True)
    except TelegramError as e:
        logger.error("Не удалось отправить заголовок /who: %s", e)
        return

    # По карточке на человека: в каждой ровно один, поэтому ответ командой
    # /dm всегда однозначен.
    for uid in chunk:
        try:
            update.message.reply_text(
                TEXT_WHO_CARD.format(
                    user=person_link(context.bot, uid),
                    dates=", ".join(key_label(k) for k in sorted(
                        on_dates[uid],
                        key=lambda k: (key_date(k) or datetime.date.max, k))),
                ),
                parse_mode='HTML', disable_web_page_preview=True)
        except TelegramError as e:
            logger.error("Не удалось отправить карточку %s: %s", uid, e)
            return
        time.sleep(0.3)   # лимит Телеграма на сообщения в группу

    last = first + len(chunk)
    if last < len(people):
        footer = TEXT_WHO_PAGE_MORE.format(
            first=first + 1, last=last, total=len(people),
            next=f"{target} {page + 1}".strip())
    else:
        footer = TEXT_WHO_PAGE_LAST.format(
            first=first + 1, last=last, total=len(people))
    update.message.reply_text(footer, parse_mode='HTML',
                              disable_web_page_preview=True)


def records_phrase(count: int) -> str:
    """'12 записей' — в нужном падеже."""
    return f"{count} " + plural_ru(count, "запись", "записи", "записей")


def replied_user_ids(message):
    """Все id людей, упомянутых в сообщении, на которое ответили.

    Возвращаем ВСЕХ, а не первого: если в сообщении несколько человек, брать
    первого попавшегося нельзя — личное сообщение молча уйдёт не тому.

    По @username id узнать нельзя: getChat принимает @имя только для каналов и
    супергрупп, но не для людей. Поэтому в сообщениях, написанных до появления
    ссылок, адресата взять неоткуда — для них есть команда /who.
    """
    found = []
    for entity in (message.entities or []):
        user_id = 0
        if entity.type == MessageEntity.TEXT_MENTION and entity.user:
            user_id = entity.user.id
        elif entity.type == MessageEntity.TEXT_LINK and entity.url:
            match = re.search(r"tg://user\?id=(\d+)", entity.url)
            if match:
                user_id = int(match.group(1))
        if user_id and user_id not in found:
            found.append(user_id)
    return found


def dm_command(update: Update, context: CallbackContext) -> None:
    """/dm текст — написать лично тому, на чьё сообщение ответили."""
    if not is_admin_chat(update):
        return

    replied = update.message.reply_to_message
    if not replied:
        update.message.reply_text(TEXT_DM_NO_REPLY, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return

    people = replied_user_ids(replied)
    if not people:
        update.message.reply_text(TEXT_DM_NO_USER, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return
    if len(people) > 1:
        # Ни в коем случае не угадываем: личное сообщение ушло бы не тому.
        update.message.reply_text(
            TEXT_DM_AMBIGUOUS.format(count=len(people)), parse_mode='HTML',
            disable_web_page_preview=True)
        return
    user_id = people[0]

    text = update.message.text.partition(' ')[2].strip()
    if not text:
        update.message.reply_text(TEXT_DM_NO_TEXT, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return

    try:
        context.bot.send_message(chat_id=user_id, text=text, parse_mode='HTML',
                                 disable_web_page_preview=True)
    except TelegramError as e:
        logger.error("Не удалось написать лично %s: %s", user_id, e)
        update.message.reply_text(TEXT_DM_FAILED.format(error=e),
            disable_web_page_preview=True)
        return

    update.message.reply_text(TEXT_DM_SENT, disable_web_page_preview=True)


def broadcast_command(update: Update, context: CallbackContext) -> None:
    """/broadcast [дата [время]] текст — показать, что уйдёт, и разослать по кнопке.

    Ответом (reply) на картинку, кружок, голосовое, гифку или видео — разослать
    и их. Сразу не уходит ничего: сначала предпросмотр и вопрос.
    """
    if not is_admin_chat(update):
        return

    # Первыми словами можно указать дату и время — тогда рассылка уйдёт
    # только тем, кто записан именно на этот вебинар.
    date_str, time_str, rest = split_target(next_word(update.message.text)[1])

    # «все» сразу после даты (без времени) — всем сеансам этого дня. Только
    # явно: без этого слова день с несколькими сеансами по-прежнему
    # отклоняется, чтобы ссылка на зум не ушла не тем.
    all_sessions = False
    if date_str and not time_str:
        word, tail = next_word(rest)
        if word.casefold() in _ALL_SESSIONS:
            all_sessions, rest = True, tail

    # Ответ на картинку, кружок и т.п. — разослать и её (текст не обязателен).
    # Ответ на файл, стикер или опрос — отказ: иначе ушёл бы один текст, без
    # того, на что ответили.
    replied = update.message.reply_to_message
    media = replied_media(replied)
    if replied and not media and (replied.effective_attachment
                                  or replied.poll or replied.dice):
        update.message.reply_text(TEXT_BROADCAST_UNSUPPORTED,
                                  disable_web_page_preview=True)
        return
    # Ответ на фото из альбома — рассылаем весь альбом. Если бот видел из
    # него меньше двух фото, лучше отказать, чем молча разослать одно.
    if media and replied.media_group_id:
        album = album_of(replied)
        if len(album) < 2:
            update.message.reply_text(TEXT_BROADCAST_ALBUM_LOST,
                                      disable_web_page_preview=True)
            return
        media = ("album", album)

    if not rest and not media:
        update.message.reply_text(TEXT_BROADCAST_USAGE, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return

    # «30.9.2026 текст» датой не распознаётся — без этой проверки рассылка
    # ушла бы всем, вместе со ссылкой, которая нужна одному вебинару.
    first_word = next_word(rest)[0]
    if not date_str and _DATE_LIKE.match(first_word):
        update.message.reply_text(
            TEXT_BROADCAST_BAD_DATE.format(token=html.escape(first_word)),
            parse_mode='HTML',
            disable_web_page_preview=True)
        return

    if date_str:
        if time_str:
            key = f"{date_str}-{re.sub(r'[^0-9]', '', time_str)}"
            if not find_webinar(key) and key not in registrations:
                update.message.reply_text(TEXT_BROADCAST_NO_WEBINAR.format(
                    date=f"{date_str} в {time_str}"),
                    disable_web_page_preview=True)
                return
            keys = [key]
        else:
            # Все сеансы дня — из расписания и из самого списка
            keys = keys_for(date_str)
            if not keys:
                update.message.reply_text(
                    TEXT_BROADCAST_NO_WEBINAR.format(date=date_str),
                    disable_web_page_preview=True)
                return
            sessions = [k for k in keys if not _DATE_ONLY.match(k)]
            if len(sessions) > 1 and not all_sessions:
                # В рассылке почти всегда ссылка на зум, а она у каждого
                # сеанса своя. Угадывать нельзя — просим указать время
                # или прямо написать «все».
                that_day = set()
                for key in keys:
                    that_day |= registered_for(key)
                items = [f"• <code>/broadcast {date_str} {key_time(k)}</code> — "
                         f"записано {len(registered_for(k))} чел."
                         for k in sessions]
                items.append(TEXT_BROADCAST_PICK_ALL.format(
                    date=date_str, count=len(that_day)))
                update.message.reply_text(
                    TEXT_BROADCAST_PICK_TIME.format(
                        date=date_str, items="\n".join(items),
                        example=f"{date_str} {key_time(sessions[0])}"),
                    parse_mode='HTML',
                    disable_web_page_preview=True)
                return
        recipients = set()
        for key in keys:
            recipients |= registered_for(key)
        recipients = reachable(recipients)
        if not recipients:
            update.message.reply_text(
                TEXT_BROADCAST_EMPTY_ONE.format(date=date_str),
                disable_web_page_preview=True)
            return
        if time_str:
            label = f"{date_str} в {time_str}"
        elif all_sessions:
            label = TEXT_BROADCAST_ALL_SESSIONS.format(date=date_str)
        else:
            label = date_str
    else:
        keys = None                               # всем записавшимся
        recipients = reachable(all_subscribers())
        if not recipients:
            update.message.reply_text(TEXT_BROADCAST_EMPTY_ALL,
                                      disable_web_page_preview=True)
            return
        label = TEXT_BROADCAST_EVERYONE

    # Дальше отправляем не голый текст, а с разметкой, которую человек навёл
    # прямо в Телеграме, и с кнопками, если он их написал.
    body = command_html(update.message, rest)
    body, buttons, complaint = split_buttons(body)
    body = link_markdown(body)
    if complaint:
        update.message.reply_text(complaint, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return
    if not body and not media:
        update.message.reply_text(TEXT_BROADCAST_USAGE, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return
    if buttons and not body and media and media[0] == "album":
        update.message.reply_text(TEXT_BROADCAST_ALBUM_NEEDS_TEXT,
                                  disable_web_page_preview=True)
        return

    # Есть варианты ответа — это опрос: у него свой номер, по нему и счёт
    poll_id = (secrets.token_hex(4) if any(url is None for _, url in buttons)
               else None)

    # Ничего не шлём сразу: сначала показываем, что уйдёт, и спрашиваем
    preview_broadcast(update, context, body, media, keys, label,
                      len(recipients), buttons, poll_id)


# Рассылки, которые показали, но ещё не отправили: id -> что и кому.
# Держим в памяти: если бот уснёт и проснётся, кнопка честно скажет, что
# предпросмотр устарел, — и ничего не уйдёт наугад.
_pending_broadcast = {}


def preview_broadcast(update, context, text, media, keys, label,
                      count, buttons=None, poll_id=None) -> None:
    """Выкладывает в группу ровно то, что уйдёт людям, и кнопки «Отправить/Отмена».

    Шлёт так же, как broadcast() — те же send_media() и caption_for(). Это и
    проверка: если здесь не вышло, людям тоже не выйдет, и спрашивать не о чем.
    """
    bot = context.bot
    caption, media_markup, text_markup = delivery_plan(media, text, buttons,
                                                       poll_id)
    try:
        if media:
            shown = send_media(bot, ADMIN_CHAT_ID, media, caption, media_markup)
            if media[0] == "album":
                remember_sent_album(shown, media[1])
        if text and not caption:
            bot.send_message(chat_id=ADMIN_CHAT_ID, text=text,
                             parse_mode='HTML', reply_markup=text_markup,
                             disable_web_page_preview=True)
    except TelegramError as e:
        reply = (TEXT_BROADCAST_BAD_MARKUP if is_markup_error(e)
                 else TEXT_BROADCAST_PREVIEW_FAILED)
        update.message.reply_text(reply.format(error=html.escape(str(e))),
                                  parse_mode='HTML',
                                  disable_web_page_preview=True)
        return
    pid = secrets.token_hex(4)
    _pending_broadcast[pid] = {"text": text, "media": media, "keys": keys,
                               "label": label, "buttons": buttons,
                               "poll_id": poll_id}
    keyboard = [[
        InlineKeyboardButton(TEXT_BROADCAST_BTN_YES, callback_data=f"bc:y:{pid}"),
        InlineKeyboardButton(TEXT_BROADCAST_BTN_NO, callback_data=f"bc:n:{pid}"),
    ]]
    update.message.reply_text(
        TEXT_BROADCAST_CONFIRM.format(label=label, count=count),
        reply_markup=InlineKeyboardMarkup(keyboard),
        disable_web_page_preview=True)


def _edit_question(query, text: str) -> None:
    """Меняет вопрос с кнопками на итог. Не вышло — не беда, главное сделано."""
    try:
        query.edit_message_text(text, disable_web_page_preview=True)
    except TelegramError as e:
        logger.warning("Не удалось обновить вопрос о рассылке: %s", e)


def broadcast_callback(update: Update, context: CallbackContext) -> None:
    """Кнопки под предпросмотром рассылки. Работают только в рабочей группе."""
    query = update.callback_query
    try:
        query.answer()
    except TelegramError as e:
        # Бот мог быть занят другой рассылкой, и Телеграм счёл нажатие
        # устаревшим. Но нажатие настоящее — выполняем его.
        logger.warning("Не удалось ответить на нажатие кнопки: %s", e)
    # CallbackQueryHandler не проходит через is_admin_chat — проверяем сами
    if not (ADMIN_CHAT_ID and query.message
            and query.message.chat.id == ADMIN_CHAT_ID):
        return
    _, action, pid = query.data.split(":", 2)
    # pop, а не get: второе нажатие той же кнопки уже ничего не найдёт
    job = _pending_broadcast.pop(pid, None)
    if job is None:
        _edit_question(query, TEXT_BROADCAST_EXPIRED)
        return
    if action != "y":
        _edit_question(query, TEXT_BROADCAST_CANCELLED)
        return
    # Кому — считаем заново: пока думали, кто-то мог записаться
    if job["keys"] is None:
        recipients = reachable(all_subscribers())
    else:
        recipients = set()
        for key in job["keys"]:
            recipients |= registered_for(key)
        recipients = reachable(recipients)
    _edit_question(query, TEXT_BROADCAST_SENDING.format(
        label=job["label"], count=len(recipients)))
    if job.get("poll_id"):
        # Счёт с нулями — до первого ответа, чтобы ни один не потерялся
        start_poll(context.bot, job["poll_id"],
                   sum(1 for _, url in job["buttons"] if url is None),
                   job.get("label", ""))
    sent, failed, _ = broadcast(context.bot, job["text"], recipients,
                                media=job["media"],
                                buttons=job.get("buttons"),
                                poll_id=job.get("poll_id"))
    notify_group(context.bot, TEXT_BROADCAST_DONE.format(sent=sent,
                                                         failed=failed))


def check_command(update: Update, context: CallbackContext) -> None:
    """/check — вручную запустить проверку напоминаний (для теста)."""
    if not is_admin_chat(update):
        return
    total = send_reminders(context.bot)
    if REMINDER_BEFORE_START:
        total += send_start_reminders(context.bot)

    # Заодно приборка: send_reminders() сохраняет список только когда реально
    # что-то отправил, поэтому без этого /check не чистит старые записи.
    cleaned = prune_resolved()
    if cleaned:
        save_registry(context.bot)

    if total == 0:
        text = TEXT_CHECK_NOTHING
        if cleaned:
            text += TEXT_CHECK_CLEANED.format(count=records_phrase(cleaned))
        update.message.reply_text(text, disable_web_page_preview=True)


