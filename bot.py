def answer_tap(query, text=None) -> None:
    """Гасит «часики» на кнопке. Не вышло — нажатие всё равно выполняем.

    Обработчики идут по одному, а рассылка на полторы сотни человек занимает
    полминуты и больше. Нажатие, дождавшееся своей очереди за ней, Телеграм
    считает устаревшим и отвечает ошибкой — раньше она вылетала ДО записи,
    и человек оставался незаписанным и без ответа.
    """
    try:
        # без этого кнопка «крутится» у пользователя; text — всплывающая
        # подсказка
        query.answer(text=text) if text else query.answer()
    except TelegramError as e:
        logger.warning("Не удалось ответить на нажатие кнопки: %s", e)


def tell_tapper(query, text: str, markup=None) -> None:
    """Ответ на нажатие: правим сообщение с кнопками, не вышло — пишем новым.

    Ответ теряться не должен: к этому моменту регистрация уже сохранена, и
    человек должен об этом узнать.
    """
    try:
        query.edit_message_text(text, parse_mode='HTML', reply_markup=markup,
                                disable_web_page_preview=True)
        return
    except TelegramError as e:
        logger.warning("Не удалось обновить сообщение с кнопками: %s", e)
    try:
        query.message.reply_text(text, parse_mode='HTML', reply_markup=markup,
                                 disable_web_page_preview=True)
    except (TelegramError, AttributeError) as e:
        logger.error("Не удалось ответить на нажатие кнопки: %s", e)


def poll_labels(markup):
    """Надписи кнопок-ответов по порядку — из самого сообщения с опросом."""
    labels = {}
    for row in (markup.inline_keyboard if markup else []):
        for button in row:
            data = button.callback_data or ""
            if data.startswith("pv:"):
                try:
                    labels[int(data.rsplit(":", 1)[1])] = button.text
                except ValueError:
                    pass
    return [labels.get(i, "?") for i in range(max(labels) + 1)] if labels else []


POLL_QUESTION_MAX = 80     # длиннее в группу не пишем — это только подпись


def poll_question(message) -> str:
    """Сам вопрос — по нему в группе видно, на какой опрос ответ.

    Берём последнюю строку текста (вопрос стоит прямо перед вариантами), а
    из неё — последнее предложение: приветствие и вопрос часто пишут одной
    строкой, и тогда в подпись попадало «Привет, были на нашем вебинаре с
    нутрициологом…», а сам вопрос обрезался. Если и предложение длинное,
    оставляем его конец: вопрос — в конце.
    """
    text = (message.text or message.caption or "").strip()
    lines = [line.strip() for line in text.split("\n") if line.strip()]
    last = lines[-1] if lines else ""
    parts = [p for p in re.split(r"(?<=[.!?…])\s+", last) if p.strip()]
    question = parts[-1].strip() if parts else last
    if len(question) > POLL_QUESTION_MAX:
        tail = question[-(POLL_QUESTION_MAX - 1):]
        # не начинаем с обрубка слова
        question = "…" + (tail.split(" ", 1)[-1] if " " in tail else tail)
    return question


def poll_callback(update: Update, context: CallbackContext) -> None:
    """Нажатие на вариант ответа под рассылкой.

    Всё нужное — вопрос, надписи, кто нажал — приходит вместе с нажатием,
    поэтому ответ переживает и перезапуск, и сон сервиса. В памяти только
    счёт, и тот записан в закрепе.
    """
    query = update.callback_query
    message = query.message
    try:
        _, poll_id, index = (query.data or "").split(":")
        index = int(index)
    except ValueError:
        answer_tap(query)
        return
    # Кнопки в предпросмотре — настоящие, но голосов там не бывает
    if message is None or message.chat.type != "private":
        answer_tap(query, TEXT_POLL_PREVIEW_TAP)
        return
    user = query.from_user
    if (poll_id, user.id) in _voted:
        answer_tap(query, TEXT_POLL_ALREADY)
        return
    labels = poll_labels(message.reply_markup)
    if not 0 <= index < len(labels):
        answer_tap(query)
        return
    # «Часики» гасим сразу: запись в закреп может ждать Телеграм дольше,
    # чем кнопка готова крутиться
    answer_tap(query)
    seen_alive(user.id)

    result = record_vote(context.bot, poll_id, index, len(labels))
    if result == VOTE_FAILED:
        # Голос не записан — кнопки остаются, человек нажмёт ещё раз
        try:
            context.bot.send_message(chat_id=user.id, text=TEXT_POLL_FAILED,
                                     disable_web_page_preview=True)
        except TelegramError as e:
            logger.warning("Не удалось ответить на голос в опросе: %s", e)
        return
    _voted.add((poll_id, user.id))

    # Кнопки-ответы убираем, ссылки (если были) оставляем: ответ учтён
    rows = message.reply_markup.inline_keyboard if message.reply_markup else []
    keep = [[b for b in row if not (b.callback_data or "").startswith("pv:")]
            for row in rows]
    keep = [row for row in keep if row]
    try:
        query.edit_message_reply_markup(
            reply_markup=InlineKeyboardMarkup(keep) if keep else None)
    except TelegramError as e:
        logger.warning("Не удалось убрать кнопки опроса: %s", e)

    answer = labels[index]
    target = poll_targets.get(poll_id, "")
    common = dict(question=html.escape(poll_question(message) or "Опрос"),
                  user=user_link(user), username=user_handle(user),
                  answer=html.escape(answer),
                  # Кому слали: без этого два опроса с одним вопросом
                  # (утро и вечер) в группе не различить
                  target=(TEXT_GROUP_POLL_TARGET.format(target=html.escape(target))
                          if target else ""))
    if result == VOTE_UNKNOWN:
        notify_group(context.bot,
                     TEXT_GROUP_POLL_ANSWER_NO_COUNT.format(**common))
    else:
        tally = " · ".join(f"{html.escape(label)} — {n}"
                           for label, n in zip(labels, result))
        notify_group(context.bot,
                     TEXT_GROUP_POLL_ANSWER.format(tally=tally, **common))
    try:
        context.bot.send_message(
            chat_id=user.id, parse_mode='HTML', disable_web_page_preview=True,
            text=TEXT_POLL_THANKS.format(answer=html.escape(answer)))
    except TelegramError as e:
        logger.warning("Не удалось поблагодарить за ответ: %s", e)


def register_callback(update: Update, context: CallbackContext) -> None:
    """Нажатие на кнопку выбора вебинара — здесь и происходит регистрация."""
    query = update.callback_query
    answer_tap(query)

    key = query.data.partition(":")[2]
    user = query.from_user
    seen_alive(user.id)
    w = find_webinar(key)

    # Кнопку могли нажать на старом сообщении — вебинар мог уже начаться
    if w is None or not webinar_is_ahead(w, as_moment()):
        tell_tapper(query, TEXT_REGISTER_GONE)
        return

    already = registered_for(key)
    if user.id in already:
        tell_tapper(query, TEXT_REGISTER_ALREADY)
        return

    # Сначала записываем и сохраняем, и только потом подтверждаем человеку —
    # иначе можно сказать «готово» там, где на самом деле ничего не сохранилось.
    registrations.setdefault(key, set()).add(user.id)
    cancelled.discard((key, user.id))   # записался снова — пометка не нужна
    remember_person(user.id, user.full_name, user.username)
    signed_at[(key, user.id)] = now_msk()
    if not save_registry(context.bot):
        registrations[key].discard(user.id)
        signed_at.pop((key, user.id), None)
        tell_tapper(query, TEXT_REGISTER_FAILED)
        return

    # Сначала группе, потом человеку: если ответ человеку почему-то не уйдёт,
    # запись всё равно сохранена и в группе она видна.
    notify_group(context.bot, TEXT_GROUP_REGISTRATION.format(
        date=f"{w['date']} в {w['time']}",
        user=user_link(user), username=user_handle(user),
    ))

    # Записался после того, как все напоминания уже разосланы: ссылку он
    # иначе не получит вовсе — шлём её прямо сейчас, тем же текстом.
    late = link_reminders_done(key)
    template = TEXT_REGISTER_DONE_SOON if late else TEXT_REGISTER_DONE
    tell_tapper(query, template.format(
        date=w["date"], time=w["time"], title=clean_title(w)))
    if late:
        if send_link_now(context.bot, w, user.id):
            logger.info("Записался поздно — ссылку на %s отправил сразу", key)
        else:
            logger.error("Не удалось сразу отправить ссылку на %s кому-то, "
                         "кто записался после всех напоминаний", key)

    # Подробности последним сообщением: «люди забывают очень быстро, на
    # что они записались». Именно последним — подтверждение обещает, что
    # СЛЕДУЮЩИМ придёт ссылка, и это обещание важнее
    details = "\n\n".join(
        part for part in (TEXT_REGISTER_DETAILS.format(
            date=w["date"], time=w["time"], title=clean_title(w),
            about=(w.get("about") or "").strip()).strip(),
            TEXT_REGISTER_DETAILS_TAIL) if part)
    try:
        context.bot.send_message(chat_id=user.id, text=details,
                                 parse_mode='HTML',
                                 disable_web_page_preview=True)
    except TelegramError as e:
        logger.warning("Не удалось отправить подробности о вебинаре: %s", e)


def my_webinars(user_id: int):
    """Вебинары этого человека, которые ещё не начались — по порядку."""
    moment = as_moment()
    mine = [w for w in WEBINARS
            if user_id in registered_for(webinar_key(w))
            and webinar_is_ahead(w, moment)]
    return sorted(mine, key=lambda x: webinar_start(x) or as_moment())


def my_command(update: Update, context: CallbackContext) -> None:
    """/my (и /link) — мои записи: ссылка на вход и отмена записи.

    Нужна и тем, кто записался после всех напоминаний или потерял сообщение.
    Чужие ссылки так не узнать: показываем только те сеансы, на которые
    записан именно этот человек, и только те, что ещё не начались.
    """
    if update.effective_chat.type != "private":
        return
    context.user_data['state'] = None
    user_id = update.effective_user.id
    seen_alive(user_id)

    mine = my_webinars(user_id)
    if not mine:
        update.message.reply_text(TEXT_LINK_NONE, parse_mode='HTML',
                                  disable_web_page_preview=True)
        return

    items, keyboard = [], []
    for w in mine:
        zoom = (w.get("zoom") or "").strip()
        template = TEXT_LINK_ITEM if zoom else TEXT_LINK_ITEM_NO_ZOOM
        items.append(template.format(date=w["date"], time=w["time"],
                                     title=clean_title(w), zoom=zoom))
        keyboard.append([InlineKeyboardButton(
            TEXT_MY_CANCEL_BUTTON.format(date=w["date"], time=w["time"]),
            callback_data=f"cx:{webinar_key(w)}")])
    update.message.reply_text(
        TEXT_LINK_HEADER + "\n\n" + "\n\n".join(items),
        parse_mode='HTML', disable_web_page_preview=True,
        reply_markup=InlineKeyboardMarkup(keyboard))


def cancel_callback(update: Update, context: CallbackContext) -> None:
    """Отмена записи: «cx:» спрашивает, «cy:» отменяет, «cn:» оставляет.

    Спрашиваем ещё раз нарочно: запись — это то, ради чего человек пришёл,
    и терять её от одного случайного нажатия он не должен.
    """
    query = update.callback_query
    answer_tap(query)
    message = query.message
    if message is None or message.chat.type != "private":
        return
    user = query.from_user
    seen_alive(user.id)
    action, _, key = (query.data or "").partition(":")

    if action == "cn":
        tell_tapper(query, TEXT_MY_CANCEL_KEPT)
        return

    w = find_webinar(key)
    # Записи может уже не быть: отменили с другого устройства, или вебинар
    # успел начаться
    if not w or user.id not in registered_for(key) or not webinar_is_ahead(w, as_moment()):
        tell_tapper(query, TEXT_MY_CANCEL_GONE)
        return

    if action == "cx":
        tell_tapper(query, TEXT_MY_CANCEL_ASK.format(
            date=w["date"], time=w["time"], title=clean_title(w)),
            markup=InlineKeyboardMarkup([[
                InlineKeyboardButton(TEXT_MY_CANCEL_YES,
                                     callback_data=f"cy:{key}"),
                InlineKeyboardButton(TEXT_MY_CANCEL_NO, callback_data="cn:"),
            ]]))
        return

    # Сначала записываем, потом говорим «отменено» — как и при регистрации
    cancelled.add((key, user.id))
    if not save_registry(context.bot):
        cancelled.discard((key, user.id))
        tell_tapper(query, TEXT_MY_CANCEL_FAILED)
        return
    notify_group(context.bot, TEXT_GROUP_CANCELLED.format(
        date=f"{w['date']} в {w['time']}",
        user=user_link(user), username=user_handle(user)))
    tell_tapper(query, TEXT_MY_CANCEL_DONE.format(date=w["date"],
                                                  time=w["time"]))


