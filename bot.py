def migrate_key(key: str) -> str:
    """Старая запись по одной дате -> ключ вебинара, если это однозначно.

    Пока вебинар в дне был один, список хранился просто по дате. Если в этот
    день вебинар по-прежнему один — переносим запись на него. Если их стало
    несколько, угадывать НЕЛЬЗЯ: человек записывался тогда, когда второго
    ещё не было, и определить какой именно он выбрал неоткуда. Такие записи
    здесь остаются как есть — на все сеансы дня их при запуске записывает
    adopt_unassigned().

    Сначала смотрим KEY_MOVES: если у вебинара поменяли время, запись должна
    переехать на новое, иначе напоминание её не найдёт.
    """
    key = KEY_MOVES.get(key, key)
    if not _DATE_ONLY.match(key):
        return key
    same_day = webinars_on(key)
    if len(same_day) == 1:
        return webinar_key(same_day[0])
    if len(same_day) > 1:
        logger.error(
            "Запись за %s осталась непривязанной: в этот день %s вебинара, "
            "а старый формат не сохранял, на какой именно записался человек. "
            "Посмотрите /stats и перезапишите их вручную.",
            key, len(same_day),
        )
    return key


def adopt_unassigned(today: datetime.date = None) -> int:
    """Старые записи «по дате» — на ВСЕ сеансы того дня, пока он впереди.

    Такой человек записывался, когда сеанс в этот день был один, а старый
    формат не сохранил, на какой именно. Выбирать за него нельзя, но и
    оставлять без напоминаний незачем: записываем на все сеансы дня, и
    напоминание каждого из них до него дойдёт. Саму строку «по дате» потом
    убирает prune_resolved(). Возвращает, скольких людей перенесли.
    """
    if today is None:
        today = today_local()
    adopted = 0
    for key in list(registrations):
        if not _DATE_ONLY.match(key) or (key_date(key) or today) < today:
            continue
        sessions = [webinar_key(w) for w in webinars_on(key)]
        if len(sessions) <= 1:
            continue
        for uid in set(registrations[key]):
            missing = [s for s in sessions if uid not in registrations.get(s, set())]
            for s in missing:
                registrations.setdefault(s, set()).add(uid)
            adopted += bool(missing)
        logger.info("Записи по дате %s перенесены на все сеансы дня: %s",
                    key, ", ".join(sessions))
    return adopted


def prune_resolved() -> int:
    """Убирает из старой записи «по дате» тех, кто уже перезаписался на
    конкретный вебинар в этот же день.

    Иначе человек навсегда остаётся сразу в двух строках: и в старой без
    времени, и в новой с временем. Старая строка так постепенно тает и в
    конце концов исчезает совсем.

    Перезапись на вебинар в ДРУГОЙ день не считается: на этот день человек
    по-прежнему непонятно куда записан.
    """
    removed = 0
    for key in list(registrations):
        if not _DATE_ONLY.match(key):
            continue
        same_day = webinars_on(key)
        if len(same_day) <= 1:
            continue
        covered = set()
        for w in same_day:
            covered |= registrations.get(webinar_key(w), set())
        resolved = registrations[key] & covered
        if resolved:
            registrations[key] -= resolved
            removed += len(resolved)
            logger.info("Убрано из непривязанных %s: %s чел. (перезаписались)",
                        key, len(resolved))
        if not registrations[key]:
            del registrations[key]
    return removed


def unassigned_keys(today: datetime.date = None):
    """Кто из старых записей по одной дате остался без вебинара.

    Возвращает {дата: множество id}. Тех, кто уже записался на конкретный
    вебинар в этот же день, НЕ считаем: напоминание они получат, и жаловаться
    на них незачем — иначе предупреждение остаётся висеть после того, как люди
    перезаписались.

    Про прошедшие даты тоже не сообщаем: напоминание о вебинаре, который уже
    был, всё равно не уйдёт, и просить этих людей перезаписаться больше не на
    что. В списке они остаются, рассылки до них доходят.
    """
    if today is None:
        today = today_local()
    stranded = {}
    for key, ids in registrations.items():
        if not ids or not _DATE_ONLY.match(key):
            continue
        if (key_date(key) or today) < today:
            continue
        same_day = webinars_on(key)
        if len(same_day) <= 1:
            continue
        covered = set()
        for w in same_day:
            covered |= registrations.get(webinar_key(w), set())
        left = ids - covered
        if left:
            stranded[key] = left
    return stranded


def all_subscribers() -> set:
    """Все, кто записан хоть на один вебинар (без повторов)."""
    everyone = set()
    for ids in registrations.values():
        everyone |= ids
    return everyone


def registered_for(key: str) -> set:
    """Кто сейчас записан на этот вебинар — без тех, кто отменил запись.

    Один источник для напоминаний, рассылок, /who и счётчиков в /stats:
    иначе где-нибудь отменившийся остался бы и получил напоминание.
    """
    ids = registrations.get(key, set())
    if not cancelled:
        return set(ids)
    return {uid for uid in ids if (key, uid) not in cancelled}


def reachable(ids) -> set:
    """Кому из них вообще можно написать: без тех, кто заблокировал бота.

    Считаем это до предпросмотра, чтобы «получателей: N» было честным.
    """
    return set(ids) - blocked


