def save_registry(bot) -> bool:
    """Сохраняет список: новый файл в группе, потом указатель на него в
    закреплённом сообщении. True — сохранено (или сохранять некуда)."""
    with _save_lock:
        return _save_registry(bot)


def _save_registry(bot) -> bool:
    global registry_message_id, file_pointer, prev_pointer, last_pin_text

    if not ADMIN_CHAT_ID:
        # Режим без группы (локальный запуск): сохранять негде, но и падать
        # незачем — про это уже написано ошибкой в лог при старте.
        return True

    # Если при старте список прочитать не удалось (сеть моргнула на холодном
    # старте), в памяти он пустой. Записать его сейчас — значит стереть всех,
    # кто уже был записан. Поэтому сначала пробуем перечитать: load_registry
    # ДОПОЛНЯЕТ память, а не заменяет её, поэтому свежая регистрация не теряется.
    if not registry_loaded:
        logger.error("Список не был прочитан при старте — перечитываю, "
                     "чтобы не затереть существующие регистрации")
        if not load_registry(bot):
            logger.error("Список по-прежнему недоступен — НИЧЕГО не пишу")
            return False

    # Кто перезаписался — того в старой строке «по дате» держать незачем
    prune_resolved()

    prune_past_sent()

    # Один снимок на всё сохранение: из него и файл, и сообщение — чтобы
    # регистрация, пришедшая посередине, не развела их «Всего».
    snap = snapshot()
    data = registry_xlsx(snap)

    # 1. Сначала новый файл. Не загрузился — ничего не поменялось.
    try:
        doc = with_retry(lambda: bot.send_document(
            chat_id=ADMIN_CHAT_ID,
            document=io.BytesIO(data),
            filename=REGISTRY_FILENAME,
            caption=TEXT_REGISTRY_FILE_CAPTION,
            disable_notification=True,
        ))
    except TelegramError as e:
        logger.error("Не удалось загрузить файл списка: %s", e)
        return False

    # 2. Потом указатель на него. Не обновился — сообщение по-прежнему
    #    указывает на старый файл, а новый просто лежит лишним. Удалять его
    #    нельзя: при обрыве связи правка могла и пройти.
    old_file, old_prev = file_pointer, prev_pointer
    file_pointer = (doc.message_id, doc.document.file_id)
    prev_pointer = old_file
    new_pin = pin_text(snap)
    try:
        if registry_message_id:
            with_retry(lambda: bot.edit_message_text(
                chat_id=ADMIN_CHAT_ID,
                message_id=registry_message_id,
                text=new_pin,
                disable_web_page_preview=True,
            ))
        else:
            msg = with_retry(lambda: bot.send_message(
                chat_id=ADMIN_CHAT_ID, text=new_pin,
                disable_web_page_preview=True))
            registry_message_id = msg.message_id
            bot.pin_chat_message(
                chat_id=ADMIN_CHAT_ID,
                message_id=msg.message_id,
                disable_notification=True,
            )
    except TelegramError as e:
        file_pointer, prev_pointer = old_file, old_prev
        logger.error("Не удалось сохранить список подписчиков: %s", e)
        return False
    last_pin_text = new_pin

    # 3. Файл старше предыдущего больше нигде не упомянут
    if old_prev and DELETE_OLD_REGISTRY_FILES:
        delete_quietly(bot, old_prev[0])
    return True


def user_link(user) -> str:
    """Имя человека ссылкой на его профиль.

    Обычный аккаунт не может написать по числовому id — нужен либо @username,
    либо вот такая ссылка. Телеграм гарантирует, что она работает для тех, кто
    уже писал боту, а это все, кто регистрировался.
    """
    return (f'<a href="tg://user?id={user.id}">'
            f'{html.escape(user.full_name)}</a>')


def user_handle(user) -> str:
    return f"@{html.escape(user.username)}" if user.username else TEXT_NO_USERNAME


def notify_group(bot, text: str) -> None:
    """Пишет в рабочую группу. Молча не теряем — при ошибке шумим в лог."""
    if not ADMIN_CHAT_ID:
        return
    try:
        # В группу Телеграм пускает ~20 сообщений в минуту, а ответы на опрос
        # и регистрации приходят пачками: короткую паузу пережидаем
        with_retry(lambda: bot.send_message(
            chat_id=ADMIN_CHAT_ID, text=text, parse_mode='HTML',
            disable_web_page_preview=True))
    except TelegramError as e:
        logger.error(
            "Не удалось написать в группу %s: %s. Проверьте ADMIN_CHAT_ID "
            "и что бот добавлен в группу.", ADMIN_CHAT_ID, e,
        )


def is_admin_chat(update: Update) -> bool:
    """Служебные команды работают только внутри рабочей группы."""
    return bool(ADMIN_CHAT_ID) and update.effective_chat.id == ADMIN_CHAT_ID


# Ошибки, после которых человека действительно незачем держать в списке:
# он заблокировал бота или удалил аккаунт. Всё остальное — таймаут, сбой сети,
# лимит Телеграма, лишний тег в тексте рассылки — временное, и вычёркивать
# человека из-за этого нельзя: он просто не получит одну рассылку.
_PERMANENT_FAILURES = (
    "bot was blocked by the user",
    "user is deactivated",
    "chat not found",
    "peer_id_invalid",
    "bot can't initiate conversation",
)


def is_permanent_failure(error) -> bool:
    """Человек ушёл навсегда (True) или это временный сбой (False)?"""
    if isinstance(error, Unauthorized):
        return True
    if isinstance(error, BadRequest):
        text = str(error).lower()
        return any(marker in text for marker in _PERMANENT_FAILURES)
    return False


# Тег HTML: <b>, </b>, <a href="...">. «<3» или «< 5» тегом не считаются.
_HTML_TAG = re.compile(r"</?[a-zA-Z][^<>]*>")
_HTML_LINK = re.compile(
    r"""<a\s[^>]*href=["']([^"']+)["'][^>]*>(.*?)</a>""", re.S | re.I)


def is_markup_error(error) -> bool:
    """Телеграм не понял HTML-разметку самого текста (у всех она одна)."""
    return (isinstance(error, BadRequest)
            and "can't parse entities" in str(error).lower())


def plain_text(text: str) -> str:
    """Тот же текст без разметки: '<b>x</b> &amp; <a href="u">y</a>' -> 'x & y (u)'."""
    text = _HTML_LINK.sub(lambda m: f"{m.group(2)} ({m.group(1)})", text)
    return html.unescape(_HTML_TAG.sub("", text))


# Что можно разослать ответом (reply) на сообщение. Гифка у Телеграма заодно
# и «файл», поэтому сначала ищем своё и только потом отказываем.
MEDIA_KINDS = ("video_note", "photo", "voice", "animation", "video")
CAPTION_LIMIT = 1024       # столько знаков Телеграм разрешает в подписи
ALBUM_KINDS = ("photo", "video")   # только из этого Телеграм собирает альбом
ALBUM_KEEP = 20                    # сколько последних альбомов помнить

# Альбомы, которые выкладывали в группу: media_group_id -> {message_id:
# (вид, file_id)}. Каждое фото альбома приходит боту отдельным сообщением —
# бот в группе администратор, а администраторы видят всё. Ответ командой
# приносит только одно фото, поэтому остальные собираем здесь. Только в
# памяти: после перезапуска альбом надо выложить заново.
_albums = {}


def remember_album_item(update: Update, context: CallbackContext) -> None:
    """Запоминает фото или видео из альбома, выложенного в группу."""
    msg = update.effective_message
    if not (msg and msg.media_group_id) or not is_admin_chat(update):
        return
    media = replied_media(msg)
    if not media or media[0] not in ALBUM_KINDS:
        return
    _keep_album(msg.media_group_id, {msg.message_id: media})


def _keep_album(group_id, items) -> None:
    """Добавляет фото к альбому в памяти; самые старые альбомы забываются."""
    group = _albums.pop(group_id, {})   # свежий — в конец очереди
    group.update(items)
    _albums[group_id] = group
    while len(_albums) > ALBUM_KEEP:
        _albums.pop(next(iter(_albums)))


def remember_sent_album(messages, items) -> None:
    """Альбом, который бот выложил сам, — в предпросмотре, — тоже в память.

    Свои сообщения бот не получает, поэтому сам по себе он их не запомнит.
    А ответить командой на эту копию после «Отмены» — самое естественное, и
    без этого бот ответил бы, что «перезапускался», хотя это неправда.
    """
    messages = list(messages or [])
    group_id = getattr(messages[0], "media_group_id", None) if messages else None
    if group_id and len(messages) == len(items):
        _keep_album(group_id, {m.message_id: item
                               for m, item in zip(messages, items)})


def album_of(message):
    """Все фото и видео альбома, к которому относится сообщение, по порядку."""
    group = _albums.get(message.media_group_id) or {}
    return tuple(group[k] for k in sorted(group))


def media_weight(media) -> int:
    """Сколько сообщений это для Телеграма: альбом из пяти фото — пять."""
    return len(media[1]) if media and media[0] == "album" else 1


def replied_media(message):
    """(вид, file_id) картинки, кружка и т.п. из сообщения — или None."""
    if message is None:
        return None
    for kind in MEDIA_KINDS:
        item = getattr(message, kind, None)
        if item:
            if kind == "photo":
                item = item[-1]    # фото приходит в нескольких размерах, последний — самый крупный
            return kind, item.file_id
    return None


def caption_for(media, text):
    """Текст, если он уйдёт подписью к медиа (одним сообщением), иначе None.

    У кружка подписи не бывает. Длину считаем с запасом — вместе с тегами и
    в единицах UTF-16, где эмодзи идёт за два: Телеграм насчитает не больше.
    """
    if not (media and text) or media[0] == "video_note":
        return None
    return text if len(text.encode("utf-16-le")) // 2 <= CAPTION_LIMIT else None


def delivery_plan(media, text, buttons, poll_id=None):
    """Как разложить рассылку по сообщениям: (подпись, кнопки медиа, кнопки текста).

    Одно правило и для предпросмотра, и для рассылки — иначе в группе
    показывалось бы одно, а людям уходило другое. Кнопки висят на том
    сообщении, которое человек увидит: на медиа с подписью, а иначе на тексте.
    У альбома кнопок не бывает — с ними текст всегда идёт отдельно.
    """
    markup = buttons_markup(buttons, poll_id)
    album = bool(media) and media[0] == "album"
    caption = None if (album and markup) else caption_for(media, text)
    separate_text = bool(text) and not caption
    media_markup = None if (album or separate_text) else markup
    text_markup = markup if separate_text else None
    return caption, media_markup, text_markup


def send_media(bot, chat_id, media, caption=None, markup=None):
    """Одно медиа по file_id: send_photo(photo=…), send_voice(voice=…) и т.д.

    Альбом — ("album", ((вид, file_id), …)) — уходит одним сообщением. Подпись
    у него одна, на первом фото, а кнопок не бывает вовсе: так устроен
    Телеграм, поэтому delivery_plan() их сюда и не даёт.
    """
    kind, file_id = media
    if kind == "album":
        items = []
        for i, (k, fid) in enumerate(file_id):
            cls = InputMediaPhoto if k == "photo" else InputMediaVideo
            items.append(cls(fid, caption=caption, parse_mode='HTML')
                         if i == 0 and caption else cls(fid))
        return bot.send_media_group(chat_id=chat_id, media=items)
    send = getattr(bot, f"send_{kind}")
    if caption:
        return send(chat_id=chat_id, caption=caption, parse_mode='HTML',
                    reply_markup=markup, **{kind: file_id})
    return send(chat_id=chat_id, reply_markup=markup, **{kind: file_id})


def broadcast(bot, text: str, recipients, markup_fallback: bool = False,
              media=None, buttons=None, poll_id=None):
    """Рассылает текст (и медиа) указанным людям.

    Возвращает (доставлено, ошибок, ошибка разметки или None).
    markup_fallback — для напоминаний, которые уходят без человека рядом: если
    Телеграм не понял HTML-разметку, тот же текст уходит всем без неё. В
    /broadcast этого нет: там ошибку ещё в предпросмотре видит тот, кто отправлял.
    media — (вид, file_id) из replied_media(): уходит каждому первым. Текст
    идёт к нему подписью, если влезает (caption_for), иначе следом отдельно.
    """
    sent, failed, gone = 0, 0, []
    parse_mode, markup_error = 'HTML', None
    caption, media_markup, text_markup = delivery_plan(media, text, buttons,
                                                       poll_id)
    for user_id in sorted(reachable(recipients)):
        try:
            media_ok = False
            if media:
                try:
                    # Телеграм просит подождать — ждём и повторяем: раньше
                    # такой человек молча оставался без рассылки
                    with_retry(lambda: send_media(bot, user_id, media, caption,
                                                  media_markup))
                    media_ok = True
                except TelegramError as e:
                    if is_permanent_failure(e):
                        raise              # человек ушёл насовсем — ниже уберём
                    if caption and not isinstance(e, BadRequest):
                        # Таймаут: сообщение с подписью могло и дойти —
                        # второй копии текста не шлём
                        raise
                    # Телеграм отказал именно в медиа (например, человек
                    # запретил голосовые и кружки) — текст со ссылкой ему
                    # всё равно нужен
                    logger.warning("%s не дошло до %s (%s) — шлю текст",
                                   media[0], user_id, e)
            body = "" if (media_ok and caption) else text
            # Медиа с подписью не дошло — текст уходит один, и кнопки с медиа
            # переезжают на него: в нём же и ссылка
            body_markup = (text_markup if (media_ok or not caption)
                           else (media_markup or text_markup))
            if body:
                try:
                    with_retry(lambda: bot.send_message(
                        chat_id=user_id, text=body, parse_mode=parse_mode,
                        reply_markup=body_markup,
                        disable_web_page_preview=True))
                except BadRequest as e:
                    if not (markup_fallback and parse_mode
                            and is_markup_error(e)):
                        raise
                    # Разметка сломана в самом тексте — значит, у всех. Этому
                    # человеку ещё раз, остальным сразу без разметки.
                    logger.error("Телеграм не понял разметку: %s — отправляю "
                                 "без форматирования", e)
                    markup_error, text, parse_mode = e, plain_text(text), None
                    body = text
                    bot.send_message(chat_id=user_id, text=body,
                                     parse_mode=None, reply_markup=body_markup,
                                     disable_web_page_preview=True)
            if media_ok or body:
                sent += 1
            else:
                failed += 1                # только медиа, и оно не дошло
        except TelegramError as e:
            failed += 1
            if is_permanent_failure(e):
                logger.info("Помечаю %s — адресат недоступен: %s", user_id, e)
                gone.append(user_id)
            else:
                logger.warning("Не доставлено %s (временная ошибка, оставляю "
                               "в списке): %s", user_id, e)
        # чтобы не упереться в лимиты Телеграма; с медиа бывает и второе
        # сообщение тому же человеку, а альбом из пяти фото для Телеграма —
        # пять сообщений, поэтому чем больше, тем медленнее
        time.sleep(0.05 * (media_weight(media) + 1) if media else 0.05)

    if gone:
        # Не удаляем: человек остаётся в списке и в файле, но с пометкой —
        # рассылки его теперь пропускают, а «Всего» не уменьшается.
        blocked.update(gone)
        save_registry(bot)
    return sent, failed, markup_error


